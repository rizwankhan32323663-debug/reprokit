let step = 0;
let failures = 0;
function check(name, cond, extra = "") {
  step += 1;
  if (cond) console.log(`  PASS ${step}. ${name}`);
  else {
    failures += 1;
    console.log(`  FAIL ${step}. ${name} ${extra}`);
  }
}

function jarFrom(setCookie) {
  if (!setCookie) return "";
  const list = Array.isArray(setCookie) ? setCookie : [setCookie];
  return list.map((c) => c.split(";")[0]).join("; ");
}

async function req(method, path, { body, cookie, form, raw, headers: extraHeaders } = {}) {
  const headers = { Origin: BASE, ...(extraHeaders ?? {}) };
  let payload;
  if (form) {
    payload = form; // FormData sets its own content-type
  } else if (raw !== undefined) {
    payload = raw; // raw bytes (Buffer) + caller-supplied Content-Type / X-* headers
  } else if (body !== undefined) {
    headers["Content-Type"] = "application/json";
    payload = JSON.stringify(body);
  } else if (method === "POST") {
    // better-auth requires a JSON content-type on POSTs (e.g. sign-out).
    headers["Content-Type"] = "application/json";
    payload = "{}";
  }
  if (cookie) headers["Cookie"] = cookie;
  const res = await fetch(`${BASE}${path}`, { method, headers, body: payload });
  const text = await res.text();
  let json = null;
  try { json = JSON.parse(text); } catch { /* non-JSON (e.g. file download) */ }
  const setCookie = res.headers.getSetCookie ? res.headers.getSetCookie() : res.headers.get("set-cookie");
  return { status: res.status, json, text, headers: res.headers, cookie: jarFrom(setCookie) };
}

function d1(query) {
  const out = execSync(
    `npx wrangler d1 execute DB --local --command ${JSON.stringify(query)} --json`,
    { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  );
  // wrangler prints non-JSON notices (e.g. proxy warning) before the JSON.
  const jsonStart = out.indexOf("[");
  return JSON.parse(jsonStart >= 0 ? out.slice(jsonStart) : out);
}

